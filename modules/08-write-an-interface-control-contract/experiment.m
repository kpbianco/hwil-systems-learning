%% P08 - Write an Interface Control Contract
close all; clc;
disp('Interface-contract question: which producer and receiver assumptions must agree before a plausible number may be released?');
disp('P08 formalizes one logical record while keeping P07 quality gating and P06 scalar observedAngleDeg unchanged.');

%% Baseline - inspect clause agreement before changing a lever
baseline = model(30.021978021978,6,1,42,true, ...
    'none','none','complete');
figure('Name','P08 baseline Interface Control Contract clauses');
bar(1:baseline.clauseCount,double(baseline.clausePass)); grid on;
ylim([0 1.2]);
set(gca,'XTick',1:baseline.clauseCount, ...
    'XTickLabel',baseline.clauseNames,'XTickLabelRotation',25, ...
    'YTick',[0 1],'YTickLabel',{'Fail','Pass'});
xlabel('Interface Control Contract clause (-)');
ylabel('Clause result (Boolean -)');
title('Baseline: all eight producer-receiver agreements pass');
assert(all(baseline.clauseEvaluated) && all(baseline.clausePass) && ...
    baseline.contractConformant && baseline.receiverAccepted && ...
    baseline.contractInputEligible && baseline.receiverInputReleased, ...
    'Every baseline clause must pass before the scalar is released.');

%% Complementary baseline view - compare only degree-valued quantities
baselineAnglesDeg = [baseline.inputs.sourceAngleDeg, ...
    baseline.payloadAngleValue,baseline.p06ObservedAngleDeg];
figure('Name','P08 baseline semantic value preservation');
plot(1:3,baselineAnglesDeg,'o-','LineWidth',1.5, ...
    'MarkerFaceColor',[0.10 0.45 0.75]); grid on;
set(gca,'XTick',1:3,'XTickLabel', ...
    {'P07-qualified source','Contract record','P06 scalar adapter'}, ...
    'XTickLabelRotation',18);
xlabel('Logical interface observation (-)'); ylabel('Position (deg)');
title('Baseline: the degree-valued scalar is preserved exactly');
assert(all(abs(baselineAnglesDeg - baselineAnglesDeg(1)) < 1e-12) && ...
    baseline.transmittedInterfaceId == 801 && ...
    baseline.transmittedChecksum == 30874 && ...
    baseline.semanticValuePreserved && baseline.p07QualityPreserved && ...
    baseline.p06ScalarContractMet, ...
    'The deterministic baseline record or scalar compatibility changed.');
fprintf(['Baseline metrics: interface %d, version %d, words %d, ' ...
    'sequence %d count, angle %.12f deg, quality %d, checksum %d count, ' ...
    'range margin %+.6f deg, accepted %d, released %d.\n'], ...
    baseline.transmittedInterfaceId,baseline.inputs.senderVersion, ...
    baseline.inputs.payloadWordCount,baseline.transmittedSequence, ...
    baseline.payloadAngleValue,baseline.wireQualityCode, ...
    baseline.transmittedChecksum,baseline.rangeMarginDeg, ...
    baseline.receiverAccepted,baseline.receiverInputReleased);

%% Sweep 1 - move only source angle against the inclusive range
sourceAngleSweepDeg = [-180 -90 0 30.021978021978 180 180.001];
rangeMarginByAngleDeg = zeros(size(sourceAngleSweepDeg));
conformantByAngle = false(size(sourceAngleSweepDeg));
releasedByAngle = false(size(sourceAngleSweepDeg));
for k = 1:numel(sourceAngleSweepDeg)
    trial = model(sourceAngleSweepDeg(k),6,1,42,true, ...
        'none','none','complete');
    rangeMarginByAngleDeg(k) = trial.rangeMarginDeg;
    conformantByAngle(k) = trial.contractConformant;
    releasedByAngle(k) = trial.receiverInputReleased;
    fprintf(['Source angle %+10.6f deg -> range margin %+10.6f deg, ' ...
        'range clause %d, accepted %d, released %d.\n'], ...
        sourceAngleSweepDeg(k),trial.rangeMarginDeg,trial.rangeMatches, ...
        trial.receiverAccepted,trial.receiverInputReleased);
    assert(trial.inputs.payloadWordCount == 6 && ...
        trial.inputs.senderVersion == 1 && trial.inputs.sequenceNumber == 42, ...
        'Sweep 1 must hold layout, version, and sequence fixed.');
end
figure('Name','P08 source-angle range sweep');
plot(sourceAngleSweepDeg,rangeMarginByAngleDeg,'o-', ...
    'LineWidth',1.5); hold on;
plot([sourceAngleSweepDeg(1) sourceAngleSweepDeg(end)],[0 0], ...
    'k--','LineWidth',1); hold off; grid on;
xlabel('Source angle (deg)'); ylabel('Contract range margin (deg)');
title('Sweep 1: +/-180 deg passes; the just-outside value is rejected');
assert(isequal(conformantByAngle,[true true true true true false]) && ...
    isequal(releasedByAngle,conformantByAngle) && ...
    rangeMarginByAngleDeg(1) == 0 && rangeMarginByAngleDeg(5) == 0 && ...
    rangeMarginByAngleDeg(6) < 0, ...
    'The angle envelope must be inclusive and reject a just-outside value.');

%% Read and explain lever 1 before advancing
disp('Mechanism after lever 1: the receiver evaluates -180 <= angleDeg <= 180; a finite value and valid checksum cannot override a failed engineering range.');
disp('This range check is an interface constraint, not a replay of P07 sensor saturation or evidence of physical angle.');

%% Sweep 2 - reset angle and move only declared payload length
payloadWordSweep = [4 5 6 7 8];
lengthClauseByWords = false(size(payloadWordSweep));
acceptedByWords = false(size(payloadWordSweep));
releasedByWords = false(size(payloadWordSweep));
for k = 1:numel(payloadWordSweep)
    trial = model(30.021978021978,payloadWordSweep(k),1,42,true, ...
        'none','none','complete');
    lengthClauseByWords(k) = trial.lengthMatches;
    acceptedByWords(k) = trial.receiverAccepted;
    releasedByWords(k) = trial.receiverInputReleased;
    fprintf(['Declared payload %2d word -> length clause %d, ' ...
        'accepted %d, released %d, checksum %d count.\n'], ...
        payloadWordSweep(k),trial.lengthMatches,trial.receiverAccepted, ...
        trial.receiverInputReleased,trial.transmittedChecksum);
    assert(abs(trial.inputs.sourceAngleDeg - baseline.inputs.sourceAngleDeg) < ...
        1e-12 && trial.inputs.senderVersion == 1, ...
        'Sweep 2 must hold source value and schema version fixed.');
end
figure('Name','P08 payload-length sweep');
stairs(payloadWordSweep,double(lengthClauseByWords),'o-', ...
    'LineWidth',1.5); hold on;
stairs(payloadWordSweep,double(acceptedByWords),'s--', ...
    'LineWidth',1.5); hold off; grid on; ylim([-0.1 1.1]);
xlabel('Declared payload length (word)');
ylabel('Length match or acceptance (Boolean -)');
legend({'Length clause passes','Receiver accepts'},'Location','northwest');
title('Sweep 2: only the exact six-word record is compatible');
assert(isequal(lengthClauseByWords,[false false true false false]) && ...
    isequal(acceptedByWords,lengthClauseByWords) && ...
    isequal(releasedByWords,lengthClauseByWords), ...
    'A plausible value cannot compensate for a short or long record.');

%% Read and explain lever 2 before advancing
disp('Mechanism after lever 2: exact record shape determines which fields exist and what they mean; extra and missing words are rejected instead of guessed.');
disp('Payload length is a logical shape fact, not transfer duration, latency, scheduling, or P11 jitter evidence.');

%% Negative cases - compatibility, integrity, quality, and transfer guards
versionBelow = model(30.021978021978,6,0,42,true, ...
    'none','none','complete');
versionAbove = model(30.021978021978,6,2,42,true, ...
    'none','none','complete');
wrongIdentity = model(30.021978021978,6,1,42,true, ...
    'identifier-mismatch','none','complete');
corrupted = model(30.021978021978,6,1,42,true, ...
    'checksum-corruption','none','complete');
invalidQualityCode = model(30.021978021978,6,1,42,true, ...
    'quality-code-invalid','none','complete');
qualityWithheld = model(30.021978021978,6,1,42,false, ...
    'none','none','complete');
assert(~versionBelow.versionMatches && ~versionBelow.receiverAccepted && ...
    ~versionAbove.versionMatches && ~versionAbove.receiverAccepted, ...
    'Only the exact supported schema version may be interpreted.');
assert(~wrongIdentity.identityMatches && ~wrongIdentity.receiverAccepted && ...
    ~corrupted.checksumMatches && ~corrupted.receiverAccepted && ...
    ~invalidQualityCode.qualityEncodingMatches && ...
    ~invalidQualityCode.receiverAccepted, ...
    'Identity, integrity, and quality-code faults must be rejected.');
assert(qualityWithheld.contractConformant && ...
    qualityWithheld.receiverAccepted && ...
    ~qualityWithheld.contractInputEligible && ...
    ~qualityWithheld.receiverInputReleased && ...
    strcmp(qualityWithheld.terminalStatus,'accepted-quality-withheld'), ...
    'A legal invalid-quality record is accepted but never released to P06.');

cancelled = model(30.021978021978,6,1,42,true, ...
    'none','cancellation','complete');
timedOut = model(30.021978021978,6,1,42,true, ...
    'none','timeout','complete');
tied = model(30.021978021978,6,1,42,true, ...
    'none','cancellation-timeout-tie','complete');
assert(cancelled.cancellationObserved && ~cancelled.transferAttempted && ...
    ~cancelled.payloadArrived && ~any(cancelled.clauseEvaluated), ...
    'Cancellation must prevent record arrival and clause evaluation.');
assert(timedOut.timeoutObserved && ~timedOut.transferAttempted && ...
    strcmp(timedOut.terminalStatus,'timed-out'), ...
    'Timeout must remain an injected pre-transfer guard.');
assert(tied.cancellationObserved && tied.timeoutObserved && ...
    tied.tieResolvedToCancellation && strcmp(tied.terminalStatus,'cancelled'), ...
    'Cancellation must retain inherited precedence in the injected tie.');
disp('Guard mechanism: cancellation and timeout are already-asserted inputs; no milliseconds, retries, or event ordering are simulated.');

%% Broken case - accept a radian-valued record from magnitude alone
strictUnitMismatch = model(30.021978021978,6,1,42,true, ...
    'unit-mismatch','none','complete');
broken = model(30.021978021978,6,1,42,true, ...
    'unit-mismatch','none','value-only');
figure('Name','P08 deliberately broken unit validation');
bar(1:5,double([strictUnitMismatch.unitMatches, ...
    strictUnitMismatch.receiverAccepted,broken.receiverAccepted, ...
    broken.receiverInputReleased,broken.semanticValuePreserved]));
grid on; ylim([0 1.2]);
set(gca,'XTick',1:5,'XTickLabel', ...
    {'Unit matches','Strict accepts','Value-only accepts', ...
    'Value-only releases','Meaning preserved'}, ...
    'XTickLabelRotation',20,'YTick',[0 1], ...
    'YTickLabel',{'No','Yes'});
xlabel('Validation evidence (-)'); ylabel('Observed result (Boolean -)');
title('Broken case: plausible magnitude hides a deg/rad mismatch');
assert(~strictUnitMismatch.unitMatches && ...
    ~strictUnitMismatch.receiverAccepted && ...
    broken.receiverAccepted && broken.receiverInputReleased && ...
    broken.falseAcceptance && broken.falseRelease && ...
    ~broken.semanticValuePreserved && ...
    abs(broken.semanticErrorDeg - ...
    (30.021978021978*pi/180 - 30.021978021978)) < 1e-12, ...
    'Value-only validation must expose false acceptance and semantic error.');
fprintf(['Broken metrics: source %.12f deg, payload %.12f rad, ' ...
    'receiver assumes %.12f deg, semantic error %+.12f deg.\n'], ...
    broken.inputs.sourceAngleDeg,broken.payloadAngleValue, ...
    broken.p06ObservedAngleDeg,broken.semanticErrorDeg);

%% Recovery and synthesis
recovered = model(30.021978021978,6,1,42,true, ...
    'none','none','complete');
assert(isequaln(recovered,baseline), ...
    'Resetting every input must recover the deterministic baseline exactly.');
disp('Synthesis: name both owners, direction, identity, version, shape, unit, range, quality, integrity, and rejection behavior before treating a received number as compatible.');
disp('P08 proves only an in-memory logical contract calculation; it does not prove MATLAB runtime, protocol, wire, device, bench, HIL, or field behavior.');
