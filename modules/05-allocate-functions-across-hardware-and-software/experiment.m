%% P05 - Allocate Functions Across Hardware and Software
close all; clc;
disp('Allocation question: which execution domain owns each P04 function, and what evidence makes that decision trustworthy?');
disp('Work units and allocation units expose resource tradeoffs without pretending to be measured execution time or hardware capacity.');

%% Baseline - preserve all ten P04 functions and inspect their owners
baseline = model('software','hardware',30,40,'available','none','complete');
figure('Name','P05 baseline function ownership');
imagesc(1:2,1:baseline.functionCount,baseline.ownerMatrix);
colormap([1 1 1; 0.10 0.45 0.75]); caxis([0 1]);
set(gca,'XTick',1:2,'XTickLabel',{'Software','Hardware'}, ...
    'YTick',1:baseline.functionCount,'YTickLabel',baseline.functionNames);
xlabel('Execution domain (-)'); ylabel('P04 function contract');
title('Baseline owner map: exactly one domain owns every function');
assert(all(baseline.ownerCountPerFunction == 1) && baseline.bindingValid, ...
    'The baseline must preserve exactly one owner and both physical endpoint bindings.');

%% Complementary baseline view - resource demand and declared capacity
figure('Name','P05 baseline resource utilization');
bar(1:2,[baseline.softwareUtilizationPercent, ...
    baseline.hardwareUtilizationPercent]); hold on;
yline(100,'--','Declared capacity'); hold off; grid on;
set(gca,'XTick',1:2,'XTickLabel',{'Software work','Hardware allocation'});
xlabel('Execution domain (-)'); ylabel('Declared capacity used (%)');
ylim([0 115]);
title(sprintf('Baseline fit: SW %.0f/%.0f work units/update; HW %.0f/%.0f allocation units', ...
    baseline.softwareDemandUnitsPerUpdate,baseline.inputs.softwareCapacity, ...
    baseline.hardwareDemandAllocationUnits,baseline.inputs.hardwareCapacity));
fprintf(['Baseline metrics: SW %.0f/%.0f work units/update (margin %.0f), ' ...
    'HW %.0f/%.0f allocation units (margin %.0f), decision %s.\n'], ...
    baseline.softwareDemandUnitsPerUpdate,baseline.inputs.softwareCapacity, ...
    baseline.softwareMarginUnitsPerUpdate, ...
    baseline.hardwareDemandAllocationUnits,baseline.inputs.hardwareCapacity, ...
    baseline.hardwareMarginAllocationUnits,baseline.decisionStatus);
assert(baseline.softwareDemandUnitsPerUpdate == 22 && ...
    baseline.hardwareDemandAllocationUnits == 22 && ...
    baseline.allocationContractMet, ...
    'The deterministic baseline allocation contract changed unexpectedly.');

%% Sweep 1 - move only the two control functions
controlSweep = {'software','hardware'};
softwareDemandByControl = zeros(1,numel(controlSweep));
hardwareDemandByControl = zeros(1,numel(controlSweep));
softwareUseByControlPercent = zeros(1,numel(controlSweep));
hardwareUseByControlPercent = zeros(1,numel(controlSweep));
for k = 1:numel(controlSweep)
    trial = model(controlSweep{k},'hardware',30,40, ...
        'available','none','complete');
    softwareDemandByControl(k) = trial.softwareDemandUnitsPerUpdate;
    hardwareDemandByControl(k) = trial.hardwareDemandAllocationUnits;
    softwareUseByControlPercent(k) = trial.softwareUtilizationPercent;
    hardwareUseByControlPercent(k) = trial.hardwareUtilizationPercent;
    fprintf(['Control owner %-8s -> SW %.0f work units/update, ' ...
        'HW %.0f allocation units, accepted %d.\n'],controlSweep{k}, ...
        trial.softwareDemandUnitsPerUpdate, ...
        trial.hardwareDemandAllocationUnits,trial.allocationContractMet);
end
figure('Name','P05 control-owner sweep');
bar(1:2,[softwareUseByControlPercent(:),hardwareUseByControlPercent(:)]); grid on;
set(gca,'XTick',1:2,'XTickLabel',{'Control in software','Control in hardware'});
xlabel('Control-function owner (-)'); ylabel('Declared capacity used (%)');
title('Lever 1: control ownership transfers demand between domains');
legend({'Software work','Hardware allocation'},'Location','best');
assert(isequal(softwareDemandByControl,[22 8]) && ...
    isequal(hardwareDemandByControl,[22 38]), ...
    'Moving only control ownership must transfer the declared control costs.');

%% Read and explain lever 1 before advancing
disp('Mechanism after lever 1: moving Compute error and Generate correction removes their work from software and consumes their declared hardware allocation instead.');
disp('The move changes resource margins; it does not prove hardware speed, scheduling, path latency, or physical performance.');

%% Sweep 2 - move only supervision under the same software-stall event
supervisionSweep = {'hardware','software'};
resourceFitBySupervision = false(1,numel(supervisionSweep));
guardAvailableBySupervision = false(1,numel(supervisionSweep));
contractBySupervision = false(1,numel(supervisionSweep));
for k = 1:numel(supervisionSweep)
    trial = model('software',supervisionSweep{k},30,40, ...
        'stalled','cancellation','complete');
    resourceFitBySupervision(k) = trial.nominalResourceFit;
    guardAvailableBySupervision(k) = trial.eventGuardAvailable;
    contractBySupervision(k) = trial.allocationContractMet;
    fprintf(['Supervision owner %-8s with stalled software -> resource fit %d, ' ...
        'cancel guard %d, safe-hold request available %d, status %s.\n'], ...
        supervisionSweep{k},trial.nominalResourceFit, ...
        trial.eventGuardAvailable,trial.safeHoldRequestAvailable, ...
        trial.scenarioStatus);
end
figure('Name','P05 supervision-owner sweep');
bar(1:2,[double(resourceFitBySupervision(:)), ...
    double(guardAvailableBySupervision(:)),double(contractBySupervision(:))]);
grid on; ylim([0 1.2]);
set(gca,'XTick',1:2, ...
    'XTickLabel',{'Supervision in hardware','Supervision in software'}, ...
    'YTick',[0 1],'YTickLabel',{'No','Yes'});
xlabel('Supervisory-function owner (-)'); ylabel('Boundary result (Boolean -)');
title('Lever 2: nominal fit does not guarantee fault-independent supervision');
legend({'Nominal resource fit','Cancellation guard available', ...
    'Full allocation contract'},'Location','best');
assert(all(resourceFitBySupervision) && ...
    isequal(guardAvailableBySupervision,[true false]) && ...
    isequal(contractBySupervision,[true false]), ...
    'Supervision ownership must isolate cancellation from application software.');

%% Read and explain lever 2 before breaking an assumption
disp('Mechanism after lever 2: Validate authority, Handle cancellation, and Enforce deadline share one fault domain; moving them into stalled application software removes the guards even though both resource totals still fit.');

%% Broken case - resource-only approval hides an unavailable cancellation guard
completeAssessment = model('software','software',30,40, ...
    'stalled','cancellation','complete');
broken = model('software','software',30,40, ...
    'stalled','cancellation','resource-only');
figure('Name','P05 broken allocation assessment');
bar(1:3,[double(broken.nominalResourceFit), ...
    double(completeAssessment.reportedFeasible), ...
    double(broken.reportedFeasible)]); grid on; ylim([0 1.2]);
set(gca,'XTick',1:3, ...
    'XTickLabel',{'Resource fit','Complete report','Broken report'}, ...
    'YTick',[0 1],'YTickLabel',{'Reject','Approve'});
xlabel('Assessment evidence (-)'); ylabel('Allocation decision (Boolean -)');
title('Broken assumption: nominal resource fit is sufficient evidence');
fprintf(['Broken metrics: nominal fit %d, cancellation handled %d, ' ...
    'full contract %d, reported feasible %d, false feasible %d, failure %s.\n'], ...
    broken.nominalResourceFit,broken.eventHandled, ...
    broken.allocationContractMet,broken.reportedFeasible, ...
    broken.falseFeasible,broken.failureMode);
assert(~completeAssessment.reportedFeasible && ...
    broken.nominalResourceFit && broken.reportedFeasible && ...
    broken.falseFeasible && ~broken.eventHandled && ...
    ~broken.safeHoldRequestAvailable, ...
    'Resource-only assessment must expose a false approval and missing guard.');

%% Recovery and mechanism synthesis
recovered = model('software','hardware',30,40,'available','none','complete');
assert(isequaln(recovered,baseline), ...
    'A fresh complete assessment must recover without hidden allocation state.');
disp('Synthesis: allocate every function once, honor physical bindings, budget both domains, and place supervisory functions outside the fault they must contain.');
disp('A safe-hold request is only an available logical output here; physical execution, path delivery, timing, and achieved safety require later evidence.');
