%% P11 - Budget Latency and Jitter
close all;
disp('Timing question: which owned nominal delays and bounded jitter allocations determine the end-to-end deadline margin?');
disp('Prediction: can every stage stay inside its own jitter allocation while an RSS total still approves a deadline that the aligned stages miss?');
disp('P11 consumes a P10 activation-proof fact; it does not execute P10 or claim that a SAFE-HOLD request performed rollback.');

%% Baseline - read the elapsed-time trace before changing a lever
baseline = model(1.2,1.0,4.2,true,Inf,'bounded-sum');
cycle = baseline.cycleIndex;
figure('Name','P11 baseline scheduled latency');
plot(cycle,baseline.plannedLatencyMs,'o--','LineWidth',1.2, ...
    'Color',[0.55 0.55 0.55],'DisplayName','Offline plan');
hold on;
plot(cycle,baseline.actualLatencyMs,'o-','LineWidth',1.7, ...
    'Color',[0.10 0.45 0.75],'MarkerFaceColor',[0.10 0.45 0.75], ...
    'DisplayName','Completed-cycle evidence');
yline(baseline.inputs.deadlineMs,'--','Deadline', ...
    'LineWidth',1.3,'DisplayName','Deadline');
hold off; grid on;
xlabel('Scheduled cycle (-)'); ylabel('End-to-end latency (ms)');
title('Baseline: fixed bounded jitter remains below the elapsed deadline');
legend('Location','best');
assert(all(baseline.cycleCompleted) && ...
    max(abs(baseline.plannedLatencyMs - ...
    [3.3 3.5 3.6 4.0 3.1 3.3 3.1 2.6 3.2 3.4 3.2 3.3])) < 1e-12 && ...
    abs(baseline.nominalLatencyMs - 3.3) < 1e-12 && ...
    abs(baseline.strictUpperBoundMs - 4.0) < 1e-12 && ...
    abs(baseline.strictMarginMs - 0.2) < 1e-12 && ...
    abs(baseline.observedPeakToPeakJitterMs - 1.4) < 1e-12 && ...
    baseline.strictBudgetAccepted && ~baseline.eventObserved, ...
    'The deterministic P11 baseline changed.');
fprintf(['Baseline metrics: nominal %.2f ms, bounded maximum %.2f ms, ' ...
    'deadline %.2f ms, margin %.2f ms, peak-to-peak jitter %.2f ms.\n'], ...
    baseline.nominalLatencyMs,baseline.strictUpperBoundMs, ...
    baseline.inputs.deadlineMs,baseline.strictMarginMs, ...
    baseline.observedPeakToPeakJitterMs);

%% Complementary baseline view - inspect cumulative stage ownership
cumulativeNominalMs = cumsum(baseline.nominalStageLatencyMs);
cumulativeJitterMs = cumsum(baseline.jitterAllocationMs);
figure('Name','P11 baseline cumulative timing envelope');
plot(1:baseline.stageCount,cumulativeNominalMs,'o-', ...
    'LineWidth',1.6,'DisplayName','Nominal cumulative latency');
hold on;
plot(1:baseline.stageCount,cumulativeNominalMs + cumulativeJitterMs, ...
    's-','LineWidth',1.6,'DisplayName','Bounded latest completion');
plot(1:baseline.stageCount,cumulativeNominalMs - cumulativeJitterMs, ...
    'd-','LineWidth',1.6,'DisplayName','Bounded earliest completion');
yline(baseline.inputs.deadlineMs,'--','Deadline','LineWidth',1.2);
hold off; grid on;
set(gca,'XTick',1:baseline.stageCount, ...
    'XTickLabel',baseline.stageNames,'XTickLabelRotation',20);
xlabel('Owned processing stage (-)');
ylabel('Cumulative elapsed time after release (ms)');
title('Complementary view: nominal delay and jitter allocation have owners');
legend('Location','northwest');

%% Sweep 1 - move only nominal command-transport latency
transportSweepMs = [0.6 1.2 1.8 2.4];
transportUpperBoundMs = zeros(size(transportSweepMs));
transportMarginMs = zeros(size(transportSweepMs));
transportPeakToPeakMs = zeros(size(transportSweepMs));
for k = 1:numel(transportSweepMs)
    trial = model(transportSweepMs(k),1.0,4.2,true,Inf, ...
        'bounded-sum');
    transportUpperBoundMs(k) = trial.strictUpperBoundMs;
    transportMarginMs(k) = trial.strictMarginMs;
    transportPeakToPeakMs(k) = trial.strictPeakToPeakJitterMs;
    assert(trial.inputs.jitterScale == 1.0 && ...
        trial.inputs.deadlineMs == 4.2 && ...
        trial.inputs.p10ActivationProof && ...
        isinf(trial.inputs.cancelAtMs) && ...
        strcmp(trial.inputs.assessmentMode,'bounded-sum'), ...
        'Sweep 1 must hold jitter, deadline, P10 proof, event, and policy fixed.');
end
figure('Name','P11 nominal transport latency sweep');
plot(transportSweepMs,transportMarginMs,'o-', ...
    'LineWidth',1.7,'MarkerFaceColor',[0.85 0.35 0.15]);
yline(0,'--','No remaining margin'); grid on;
xlabel('Command-transport nominal latency (ms)');
ylabel('Worst-case deadline margin (ms)');
title('Sweep 1: nominal transport delay shifts the whole timing envelope');
assert(max(abs(transportUpperBoundMs - [3.4 4.0 4.6 5.2])) < 1e-12 && ...
    max(abs(transportMarginMs - [0.8 0.2 -0.4 -1.0])) < 1e-12 && ...
    max(abs(transportPeakToPeakMs - 1.4)) < 1e-12, ...
    'Transport sweep must move nominal latency without changing jitter width.');

%% Read and explain lever 1 before advancing
disp('Mechanism after lever 1: transport latency adds one-for-one to nominal and worst-case latency, so deadline margin shrinks by the same milliseconds.');
disp('The per-stage jitter allocations did not move, so the bounded peak-to-peak jitter stayed fixed.');

%% Sweep 2 - reset transport and move only jitter scale
jitterScaleSweep = [0 0.5 1.0 1.5 2.0];
jitterUpperBoundMs = zeros(size(jitterScaleSweep));
jitterMarginMs = zeros(size(jitterScaleSweep));
jitterPeakToPeakMs = zeros(size(jitterScaleSweep));
for k = 1:numel(jitterScaleSweep)
    trial = model(1.2,jitterScaleSweep(k),4.2,true,Inf, ...
        'bounded-sum');
    jitterUpperBoundMs(k) = trial.strictUpperBoundMs;
    jitterMarginMs(k) = trial.strictMarginMs;
    jitterPeakToPeakMs(k) = trial.strictPeakToPeakJitterMs;
    assert(trial.inputs.transportNominalMs == 1.2 && ...
        trial.inputs.deadlineMs == 4.2 && ...
        trial.inputs.p10ActivationProof && ...
        isinf(trial.inputs.cancelAtMs) && ...
        strcmp(trial.inputs.assessmentMode,'bounded-sum'), ...
        'Sweep 2 must reset transport and hold deadline, P10 proof, event, and policy fixed.');
end
figure('Name','P11 bounded jitter sweep');
plot(jitterScaleSweep,jitterMarginMs,'s-', ...
    'LineWidth',1.7,'MarkerFaceColor',[0.50 0.20 0.70]);
yline(0,'--','No remaining margin'); grid on;
xlabel('Jitter-allocation scale (-)');
ylabel('Worst-case deadline margin (ms)');
title('Sweep 2: wider bounded variation consumes deadline margin');
assert(max(abs(jitterUpperBoundMs - ...
    [3.3 3.65 4.0 4.35 4.7])) < 1e-12 && ...
    max(abs(jitterMarginMs - [0.9 0.55 0.2 -0.15 -0.5])) < 1e-12 && ...
    max(abs(jitterPeakToPeakMs - [0 0.7 1.4 2.1 2.8])) < 1e-12, ...
    'Jitter sweep must widen the envelope without moving nominal latency.');

%% Read and explain lever 2 before advancing
disp('Mechanism after lever 2: bounded end-to-end jitter is the sum of owned stage allocations when simultaneous signs are not excluded.');
disp('The nominal latency stayed fixed while the latest and earliest completions separated symmetrically.');

%% Negative cases - unavailable proof, cancellation, timeout, and recovery
blocked = model(1.2,1.0,4.2,false,Inf,'bounded-sum');
cancelled = model(1.2,1.0,4.2,true,15.0,'bounded-sum');
completionTied = model(1.2,1.0,4.2,true,9.5,'bounded-sum');
timedOut = model(1.2,2.0,4.2,true,Inf,'bounded-sum');
tied = model(1.2,2.0,4.2,true,22.2,'bounded-sum');
assert(~any(blocked.cycleStarted) && ...
    all(isnan(blocked.actualLatencyMs)) && ...
    strcmp(blocked.terminalStatus,'blocked-p10-activation-proof') && ...
    ~blocked.safeHoldRequested, ...
    'Missing P10 activation proof must block execution without inventing a handoff.');
assert(isequal(cancelled.cycleStarted, ...
    [true true true false false false false false false false false false]) && ...
    isequal(cancelled.cycleCompleted, ...
    [true true false false false false false false false false false false]) && ...
    all(isnan(cancelled.actualLatencyMs(3:end))) && ...
    cancelled.cancellationObserved && ~cancelled.timeoutObserved && ...
    cancelled.safeHoldRequested && cancelled.rollbackRequired && ...
    ~cancelled.rollbackEvidenceAvailable && ...
    strcmp(cancelled.rollbackAuthority,'P10'), ...
    'Cancellation must mask unfinished facts and request, not claim, rollback.');
assert(isequal(completionTied.cycleStarted, ...
    [true true false false false false false false false false false false]) && ...
    isequal(completionTied.cycleCompleted, ...
    [true false false false false false false false false false false false]) && ...
    completionTied.cancellationObserved && ...
    ~completionTied.timeoutObserved && ...
    completionTied.interruptedCycle == 2 && ...
    abs(completionTied.terminalTimeMs - 9.5) < 1e-12, ...
    'Cancellation must win an exact tie with planned completion.');
assert(isequal(timedOut.cycleCompleted, ...
    [true true true false false false false false false false false false]) && ...
    timedOut.timeoutObserved && timedOut.interruptedCycle == 4 && ...
    abs(timedOut.terminalTimeMs - 22.2) < 1e-12 && ...
    all(isnan(timedOut.actualLatencyMs(4:end))), ...
    'Timeout must be derived at the first deadline before late completion.');
assert(tied.cancellationObserved && tied.timeoutObserved && ...
    tied.tieResolvedToCancellation && tied.interruptedCycle == 4 && ...
    strcmp(tied.terminalStatus,'cancelled-on-timeout-tie'), ...
    'Cancellation must win the cancellation/deadline tie.');
recovered = model(1.2,1.0,4.2,true,Inf,'bounded-sum');
assert(isequaln(recovered,baseline), ...
    'A fresh valid call after blocked or interrupted cases must recover exactly.');

%% Deliberately broken case - assume unproven stage independence
strictCase = model(1.2,2.0,4.2,true,Inf,'bounded-sum');
broken = model(1.2,2.0,4.2,true,Inf,'rss-uncorrelated');
figure('Name','P11 deliberately broken RSS assessment');
bar([broken.reportedUpperBoundMs broken.strictUpperBoundMs ...
    max(broken.plannedLatencyMs) broken.inputs.deadlineMs]);
grid on;
set(gca,'XTick',1:4,'XTickLabel', ...
    {'Broken RSS report','Bounded sum','Aligned cycle','Deadline'}, ...
    'XTickLabelRotation',15);
ylabel('End-to-end latency (ms)');
title('Broken case: unproven independence creates a false approval');
assert(isequal(strictCase.jitterPattern,broken.jitterPattern) && ...
    max(abs(strictCase.plannedLatencyMs - ...
    broken.plannedLatencyMs)) < 1e-12 && ...
    abs(broken.strictUpperBoundMs - 4.7) < 1e-12 && ...
    abs(broken.reportedUpperBoundMs - ...
    (3.3 + sqrt(0.6))) < 1e-12 && ...
    ~broken.strictBudgetAccepted && broken.reportedBudgetAccepted && ...
    broken.falseApproval && ~broken.assessmentDecisionCorrect && ...
    broken.timeoutObserved && broken.interruptedCycle == 4 && ...
    strcmp(broken.reportingFailureMode, ...
    'rss-independence-false-approval'), ...
    'Broken RSS assessment must preserve the facts and expose false approval.');
disp('Broken mechanism: RSS cancellation needs evidence of independent stage variation; the fixed aligned row keeps every stage inside its allocation but reaches the additive 4.7 ms bound.');

