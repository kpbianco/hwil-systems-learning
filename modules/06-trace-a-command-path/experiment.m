%% P06 - Trace a Command Path
close all; clc;
disp('Command-path question: which owned function and boundary sees the command, and where does its value or evidence stop?');
disp('The endpoint is a logical actuator input latch. Receipt is not physical motion, achieved safe hold, or measurement-path evidence.');

%% Baseline - inspect reachability before changing a lever
baseline = model(30,0,45,0.35,'none','none','endpoint-receipt');
figure('Name','P06 baseline command-path reachability');
bar(1:baseline.stageCount,double(baseline.stageReached)); grid on; ylim([0 1.2]);
set(gca,'XTick',1:baseline.stageCount,'XTickLabel',baseline.stageNames, ...
    'XTickLabelRotation',25,'YTick',[0 1],'YTickLabel',{'No','Yes'});
xlabel('P04/P05 command-path stage (-)'); ylabel('Stage reached (Boolean -)');
title('Baseline trace: all owned stages reach the actuator input latch');
assert(all(baseline.stageReached) && all(baseline.boundaryCrossed) && ...
    baseline.actuatorCommandReceived && baseline.traceContractMet, ...
    'Every baseline boundary must carry the logical command to the endpoint.');

%% Complementary baseline view - trace degree-valued lineage only
figure('Name','P06 baseline angle lineage');
plot(1:3,baseline.stageOutputValue(1:3),'o-', ...
    'LineWidth',1.5,'MarkerFaceColor',[0.10 0.45 0.75]); grid on;
set(gca,'XTick',1:3,'XTickLabel',baseline.stageNames(1:3), ...
    'XTickLabelRotation',20);
xlabel('Command calculation stage (-)'); ylabel('Stage output (deg)');
title('Target is preserved through authority, then combined with the named observation');
assert(isequal(baseline.stageOutputValue(1:3),[30 30 30]) && ...
    baseline.authorityMarginDeg == 15, ...
    'Baseline degree lineage must preserve target and compute 30 deg error.');

%% Complementary baseline view - keep correction units separate
figure('Name','P06 baseline correction lineage');
plot(4:5,baseline.stageOutputValue(4:5),'s-', ...
    'LineWidth',1.5,'MarkerFaceColor',[0.85 0.45 0.10]); grid on;
set(gca,'XTick',4:5,'XTickLabel',baseline.stageNames(4:5), ...
    'XTickLabelRotation',20);
xlabel('Command delivery stage (-)'); ylabel('Correction (deg/update)');
title('Generated correction equals the actuator-latch value at the final handoff');
fprintf(['Baseline metrics: request %.0f deg, observation %.0f deg, ' ...
    'error %.1f deg, fraction %.2f, correction %.1f deg/update, ' ...
    'crossed boundaries %d/%d, terminal %s.\n'], ...
    baseline.inputs.requestedAngleDeg,baseline.inputs.observedAngleDeg, ...
    baseline.errorDeg,baseline.inputs.responseFraction, ...
    baseline.correctionDegPerUpdate,baseline.crossedBoundaryCount, ...
    baseline.boundaryCount,baseline.terminalStatus);
assert(abs(baseline.correctionDegPerUpdate - 10.5) < 1e-12 && ...
    baseline.payloadPreservedToEndpoint, ...
    'The endpoint must receive the exact generated correction.');

%% Sweep 1 - move only the authority-limit lever
authoritySweepDeg = [20 30 45 90];
deepestStageByAuthority = zeros(size(authoritySweepDeg));
endpointReceiptByAuthority = false(size(authoritySweepDeg));
for k = 1:numel(authoritySweepDeg)
    trial = model(30,0,authoritySweepDeg(k),0.35, ...
        'none','none','endpoint-receipt');
    deepestStageByAuthority(k) = trial.deepestReachedStage;
    endpointReceiptByAuthority(k) = trial.actuatorCommandReceived;
    fprintf(['Authority limit +/-%.0f deg -> deepest stage %d, ' ...
        'terminal %s, endpoint receipt %d.\n'],authoritySweepDeg(k), ...
        trial.deepestReachedStage,trial.terminalStatus, ...
        trial.actuatorCommandReceived);
end
figure('Name','P06 authority-limit sweep');
yyaxis left;
plot(authoritySweepDeg,deepestStageByAuthority,'o-', ...
    'LineWidth',1.5,'MarkerFaceColor',[0.10 0.45 0.75]);
ylabel('Deepest stage reached (-)'); ylim([0 baseline.stageCount + 1]);
yyaxis right;
stairs(authoritySweepDeg,double(endpointReceiptByAuthority),'s-', ...
    'LineWidth',1.5);
ylabel('Actuator input received (Boolean -)'); ylim([-0.1 1.1]);
grid on; xlabel('Symmetric authority limit (deg)');
title('Sweep 1: authority changes reachability without changing the request');
assert(isequal(deepestStageByAuthority,[2 5 5 5]) && ...
    isequal(endpointReceiptByAuthority,[false true true true]), ...
    'The 30 deg request must fail below, but pass at, the authority limit.');

%% Read and explain lever 1 before advancing
disp('Mechanism after lever 1: the same 30 deg target reaches Validate authority; the inclusive |request| <= limit guard alone decides whether downstream stages become reachable.');
disp('A handled rejection raises a logical safe-hold requirement but does not prove any physical hold action.');

%% Sweep 2 - open one boundary at a time
boundarySweep = {'none','request-to-authority','authority-to-error', ...
    'error-to-correction','correction-to-actuator'};
deepestStageByBoundary = zeros(1,numel(boundarySweep));
endpointReceiptByBoundary = false(1,numel(boundarySweep));
for k = 1:numel(boundarySweep)
    trial = model(30,0,45,0.35,boundarySweep{k}, ...
        'none','endpoint-receipt');
    deepestStageByBoundary(k) = trial.deepestReachedStage;
    endpointReceiptByBoundary(k) = trial.actuatorCommandReceived;
    fprintf(['Open boundary %-24s -> deepest stage %d, ' ...
        'crossed %d boundaries, terminal %s.\n'],boundarySweep{k}, ...
        trial.deepestReachedStage,trial.crossedBoundaryCount, ...
        trial.terminalStatus);
end
figure('Name','P06 open-boundary sweep');
bar(1:numel(boundarySweep),deepestStageByBoundary); grid on;
set(gca,'XTick',1:numel(boundarySweep), ...
    'XTickLabel',{'None','B1','B2','B3','B4'});
xlabel('Open command boundary (-)'); ylabel('Deepest stage reached (-)');
title('Sweep 2: first missing handoff localizes the stopped path');
assert(isequal(deepestStageByBoundary,[5 1 2 3 4]) && ...
    isequal(endpointReceiptByBoundary,[true false false false false]), ...
    'Each open boundary must stop the trace at its source stage.');

%% Read and explain lever 2 before breaking an assumption
disp('Mechanism after lever 2: a stage can produce a valid local output while the next owner never receives it; reachability is a contiguous prefix ending at the first open boundary.');
disp('Boundary labels describe logical ownership handoffs, not P08 message layouts or P11 timing.');

%% Guarded terminals - observe cancellation, timeout, and their tie
cancelled = model(30,0,45,0.35,'none', ...
    'cancellation','endpoint-receipt');
timedOut = model(30,0,45,0.35,'none','timeout','endpoint-receipt');
tied = model(30,0,45,0.35,'none', ...
    'cancellation-timeout-tie','endpoint-receipt');
assert(cancelled.cancellationObserved && cancelled.safeHoldRequired && ...
    ~cancelled.actuatorCommandReceived && strcmp(cancelled.terminalStatus,'cancelled'), ...
    'Cancellation must stop the final handoff and require a logical safe response.');
assert(timedOut.timeoutObserved && timedOut.safeHoldRequired && ...
    ~timedOut.actuatorCommandReceived && strcmp(timedOut.terminalStatus,'timed-out'), ...
    'An injected timeout must stop the final handoff without claiming elapsed-time evidence.');
assert(tied.cancellationObserved && tied.timeoutObserved && ...
    tied.tieResolvedToCancellation && strcmp(tied.terminalStatus,'cancelled'), ...
    'Cancellation must retain P04 precedence in the injected tie.');
disp('Guard mechanism: cancellation and timeout are already-asserted inputs at the final handoff; they are not serial processing delay or measured time.');

%% Broken case - local dispatch masquerades as endpoint receipt
completeAssessment = model(30,0,45,0.35, ...
    'correction-to-actuator','none','endpoint-receipt');
broken = model(30,0,45,0.35, ...
    'correction-to-actuator','none','dispatch-only');
figure('Name','P06 broken dispatch-only assessment');
bar(1:3,[double(broken.localDispatchObserved), ...
    double(completeAssessment.reportedSuccess), ...
    double(broken.reportedSuccess)]); grid on; ylim([0 1.2]);
set(gca,'XTick',1:3,'XTickLabel', ...
    {'Local dispatch','Endpoint-receipt report','Broken dispatch-only report'}, ...
    'YTick',[0 1],'YTickLabel',{'No','Yes'});
xlabel('Evidence checkpoint (-)'); ylabel('Reported delivery success (Boolean -)');
title('Broken assumption: a generated command proves endpoint receipt');
fprintf(['Broken metrics: local dispatch %d, final boundary crossed %d, ' ...
    'endpoint receipt %d, reported success %d, false success %d.\n'], ...
    broken.localDispatchObserved,broken.boundaryCrossed(4), ...
    broken.actuatorCommandReceived,broken.reportedSuccess,broken.falseSuccess);
assert(broken.localDispatchObserved && ~broken.boundaryCrossed(4) && ...
    ~broken.actuatorCommandReceived && broken.reportedSuccess && ...
    broken.falseSuccess && ~completeAssessment.reportedSuccess, ...
    'Dispatch-only evidence must expose false success at the final boundary.');

%% Recovery and mechanism synthesis
recovered = model(30,0,45,0.35,'none','none','endpoint-receipt');
assert(isequaln(recovered,baseline), ...
    'A fresh valid trace must recover without hidden command-path state.');
disp('Synthesis: trace the unit-bearing value, owner, boundary crossing, terminal guard, and endpoint evidence; stop the explanation at the first missing handoff.');
disp('The endpoint receipt is logical command delivery only. P07 owns measurement data, P08 owns interface contracts, and P11 owns timing and jitter.');
