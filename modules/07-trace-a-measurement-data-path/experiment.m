%% P07 - Trace a Measurement Data Path
close all; clc;
disp('Measurement-path question: which owner receives the value and validity flag, and where can either stop or become misleading?');
disp('The endpoint is P07''s qualified-control intake. P06 accepts only scalar observedAngleDeg, so P07 gates that scalar with p06InputEligible instead of adding a validity input.');

%% Baseline - inspect reachability before changing a lever
baseline = model(30,12,5,20,'none','none','complete');
figure('Name','P07 baseline measurement-path reachability');
bar(1:baseline.stageCount,double(baseline.stageReached)); grid on; ylim([0 1.2]);
set(gca,'XTick',1:baseline.stageCount,'XTickLabel',baseline.stageNames, ...
    'XTickLabelRotation',25,'YTick',[0 1],'YTickLabel',{'No','Yes'});
xlabel('Measurement data stage (-)'); ylabel('Stage reached (Boolean -)');
title('Baseline trace: value and quality reach the P07 qualified intake');
assert(all(baseline.stageReached) && all(baseline.boundaryCrossed) && ...
    baseline.endpointReceived && baseline.traceContractMet, ...
    'The baseline sample must cross all four logical handoffs.');

%% Complementary baseline view - compare only degree-valued quantities
degreeLineage = [baseline.inputs.trueAngleDeg, ...
    baseline.sensorEquivalentAngleDeg,baseline.calibratedAngleDeg, ...
    baseline.stageOutputValue(4),baseline.stageOutputValue(5)];
figure('Name','P07 baseline engineering-value lineage');
plot(1:5,degreeLineage,'o-','LineWidth',1.5, ...
    'MarkerFaceColor',[0.10 0.45 0.75]); grid on;
set(gca,'XTick',1:5,'XTickLabel', ...
    {'Model truth reference','Sensor equivalent','Calibrated', ...
    'Qualified payload','P07 qualified intake'},'XTickLabelRotation',20);
xlabel('Comparable measurement view (-)'); ylabel('Position (deg)');
title('Value lineage: quantization changes the value while quality remains explicit');
assert(abs(baseline.sensorVolts - 2.833333333333333) < 1e-12 && ...
    baseline.adcCount == 2389 && ...
    abs(baseline.calibratedAngleDeg - 30.021978021978) < 1e-12 && ...
    baseline.qualityValid && baseline.measurementUsable && ...
    baseline.p06InputEligible && ...
    baseline.p06ObservedAngleDeg == baseline.stageOutputValue(5), ...
    'Baseline voltage, count, calibrated value, and validity changed.');
fprintf(['Baseline metrics: truth %.1f deg, sensor %.6f V, ADC %d/%d count, ' ...
    'calibrated %.6f deg, error %+.6f deg, LSB %.6f deg, ' ...
    'age %.1f ms, freshness margin %+.1f ms, usable %d.\n'], ...
    baseline.inputs.trueAngleDeg,baseline.sensorVolts,baseline.adcCount, ...
    baseline.maxAdcCount,baseline.calibratedAngleDeg, ...
    baseline.measurementErrorDeg,baseline.quantizationStepDeg, ...
    baseline.inputs.sampleAgeMs,baseline.freshnessMarginMs, ...
    baseline.measurementUsable);

%% Sweep 1 - move only ADC resolution
adcBitSweep = [6 8 10 12];
adcCountByBits = zeros(size(adcBitSweep));
quantizationStepByBitsDeg = zeros(size(adcBitSweep));
absoluteErrorByBitsDeg = zeros(size(adcBitSweep));
for k = 1:numel(adcBitSweep)
    trial = model(30,adcBitSweep(k),5,20,'none','none','complete');
    adcCountByBits(k) = trial.adcCount;
    quantizationStepByBitsDeg(k) = trial.quantizationStepDeg;
    absoluteErrorByBitsDeg(k) = abs(trial.quantizationErrorDeg);
    fprintf(['ADC %2d bit -> %5d count, LSB %.6f deg/count, ' ...
        'quantization error %+.6f deg.\n'],adcBitSweep(k),trial.adcCount, ...
        trial.quantizationStepDeg,trial.quantizationErrorDeg);
    assert(trial.inputs.sampleAgeMs == 5 && ...
        trial.inputs.freshnessLimitMs == 20 && trial.qualityValid, ...
        'Sweep 1 must hold freshness inputs and path quality fixed.');
end
figure('Name','P07 ADC-resolution sweep');
semilogy(adcBitSweep,quantizationStepByBitsDeg,'o-', ...
    adcBitSweep,absoluteErrorByBitsDeg,'s-','LineWidth',1.5); grid on;
xlabel('ADC resolution (bit)'); ylabel('Angle magnitude (deg)');
legend({'Quantization step','Observed absolute quantization error'}, ...
    'Location','southwest');
title('Sweep 1: more bits tighten the quantization envelope');
assert(isequal(adcCountByBits,[37 149 597 2389]) && ...
    all(diff(quantizationStepByBitsDeg) < 0) && ...
    all(absoluteErrorByBitsDeg <= 0.5*quantizationStepByBitsDeg + 1e-12), ...
    'ADC counts and half-LSB quantization bounds must remain transparent.');

%% Read and explain lever 1 before advancing
disp('Mechanism after lever 1: bit depth changes maxCount = 2^bits - 1 and LSB = 360/maxCount deg; it does not change sample age, path reachability, or validity.');
disp('A tighter LSB bounds quantization error, but it does not prove every arbitrary sample error decreases monotonically.');

%% Sweep 2 - reset resolution and move only sample age
sampleAgeSweepMs = [0 10 20 21 40];
freshByAge = false(size(sampleAgeSweepMs));
usableByAge = false(size(sampleAgeSweepMs));
endpointByAge = false(size(sampleAgeSweepMs));
calibratedByAgeDeg = zeros(size(sampleAgeSweepMs));
for k = 1:numel(sampleAgeSweepMs)
    trial = model(30,12,sampleAgeSweepMs(k),20, ...
        'none','none','complete');
    freshByAge(k) = trial.freshnessCriterionMet;
    usableByAge(k) = trial.measurementUsable;
    endpointByAge(k) = trial.endpointReceived;
    calibratedByAgeDeg(k) = trial.calibratedAngleDeg;
    fprintf(['Sample age %5.1f ms -> margin %+5.1f ms, endpoint %d, ' ...
        'quality valid %d, usable %d.\n'],sampleAgeSweepMs(k), ...
        trial.freshnessMarginMs,trial.endpointReceived, ...
        trial.qualityValid,trial.measurementUsable);
    assert(trial.inputs.adcBits == 12 && trial.adcCount == 2389, ...
        'Sweep 2 must hold resolution and the decoded value fixed.');
end
figure('Name','P07 sample-age sweep');
stairs(sampleAgeSweepMs,double(freshByAge),'o-','LineWidth',1.5); hold on;
stairs(sampleAgeSweepMs,double(usableByAge),'s--','LineWidth',1.5); hold off;
grid on; ylim([-0.1 1.1]);
xlabel('Supplied sample age (ms)'); ylabel('Validity or usability (Boolean -)');
legend({'Freshness criterion met','Measurement usable'},'Location','southwest');
title('Sweep 2: equality passes; one millisecond beyond the limit is stale');
assert(isequal(freshByAge,[true true true false false]) && ...
    isequal(usableByAge,freshByAge) && all(endpointByAge) && ...
    all(abs(calibratedByAgeDeg - calibratedByAgeDeg(1)) < 1e-12), ...
    'Age must change quality without changing value or endpoint reachability.');

%% Read and explain lever 2 before breaking an assumption
disp('Mechanism after lever 2: age metadata does not alter the calibrated number or handoff reachability; the inclusive age <= limit rule changes local validity and P06 scalar-input eligibility.');
disp('P07 evaluates supplied age metadata only. P11 later owns how latency, scheduling, and jitter produce that age.');

%% Acquisition guards - cancellation, timeout, and inherited precedence
cancelled = model(30,12,5,20,'none','cancellation','complete');
timedOut = model(30,12,5,20,'none','timeout','complete');
tied = model(30,12,5,20,'none', ...
    'cancellation-timeout-tie','complete');
assert(cancelled.cancellationObserved && ~any(cancelled.stageReached) && ...
    strcmp(cancelled.terminalStatus,'cancelled') && cancelled.traceContractMet, ...
    'A pre-asserted cancellation must prevent a sample from entering the path.');
assert(timedOut.timeoutObserved && ~any(timedOut.stageReached) && ...
    strcmp(timedOut.terminalStatus,'timed-out') && timedOut.traceContractMet, ...
    'A pre-asserted timeout must prevent sample entry without claiming elapsed timing.');
assert(tied.cancellationObserved && tied.timeoutObserved && ...
    tied.tieResolvedToCancellation && strcmp(tied.terminalStatus,'cancelled'), ...
    'Cancellation must retain inherited precedence in the injected tie.');
disp('Guard mechanism: cancellation and timeout are already-asserted acquisition inputs, not measured delay, scheduler behavior, or a physical safe-state claim.');

%% Quality failure - saturation remains distinguishable from a missing sample
saturated = model(181,12,5,20,'none','none','complete');
assert(saturated.endpointReceived && saturated.qualityEvaluated && ...
    saturated.sensorSaturated && ~saturated.qualityValid && ...
    ~saturated.measurementUsable && ~saturated.p06InputEligible && ...
    isnan(saturated.p06ObservedAngleDeg) && ...
    strcmp(saturated.failureMode,'sensor-saturated'), ...
    'A saturated sample must arrive with invalid quality rather than vanish.');

%% Broken case - a finite stale value masquerades as usable data
completeStale = model(30,12,21,20,'none','none','complete');
broken = model(30,12,21,20,'none','none','value-only');
figure('Name','P07 broken value-only assessment');
bar(1:4,[double(broken.endpointReceived),double(broken.qualityValid), ...
    double(broken.p06InputEligible),double(broken.reportedUsable)]);
grid on; ylim([0 1.2]);
set(gca,'XTick',1:4,'XTickLabel', ...
    {'P07 endpoint received','Quality valid','P06 input eligible','Broken value-only report'}, ...
    'XTickLabelRotation',20,'YTick',[0 1],'YTickLabel',{'No','Yes'});
xlabel('Evidence used by the assessment (-)');
ylabel('Reported measurement usability (Boolean -)');
title('Broken assumption: a finite received number must be usable');
fprintf(['Broken metrics: value %.6f deg, age %.1f ms, limit %.1f ms, ' ...
    'quality valid %d, reported usable %d, false usable %d.\n'], ...
    broken.calibratedAngleDeg,broken.inputs.sampleAgeMs, ...
    broken.inputs.freshnessLimitMs,broken.qualityValid, ...
    broken.reportedUsable,broken.falseUsable);
assert(isequal(completeStale.stageReached,broken.stageReached) && ...
    isequal(completeStale.boundaryCrossed,broken.boundaryCrossed) && ...
    completeStale.calibratedAngleDeg == broken.calibratedAngleDeg && ...
    completeStale.qualityValid == broken.qualityValid && ...
    completeStale.endpointReceived && ~completeStale.measurementUsable && ...
    ~completeStale.p06InputEligible && ~broken.p06InputEligible && ...
    isnan(completeStale.p06ObservedAngleDeg) && ...
    isnan(broken.p06ObservedAngleDeg) && ...
    ~completeStale.reportedUsable && broken.reportedUsable && ...
    broken.falseUsable, ...
    'Value-only assessment may change only the report, never path or quality truth.');

%% Recovery and mechanism synthesis
recovered = model(30,12,5,20,'none','none','complete');
assert(isequaln(recovered,baseline), ...
    'A fresh valid trace must recover without hidden measurement-path state.');
disp('Synthesis: trace the unit-bearing payload, owner, boundary, quality flag, and endpoint evidence; distinguish missing, received-invalid, received-valid, and usable data.');
disp('P07 ends at a local qualified-control intake and exposes P06''s unchanged scalar only when p06InputEligible is true. P08 owns interface contracts, P11 timing and jitter, and P20 calibration-state control.');
