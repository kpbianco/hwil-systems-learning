function run_checks
%RUN_CHECKS Independent P07 measurement value, quality, and path checks.
baseline = model(30,12,5,20,'none','none','complete');
repeat = model(30,12,5,20,'none','none','complete');
defaults = model();
assert(isequaln(baseline,repeat) && isequaln(defaults,baseline), ...
    'Repeated and default baseline calls must be deterministic and stateless.');
assertTraceInvariant(baseline);

expectedStageNames = { ...
    'Observe position sensor', ...
    'Digitize sensor voltage', ...
    'Calibrate to engineering units', ...
    'Qualify sample', ...
    'P07 qualified-control intake'};
expectedStageOwners = { ...
    'sensor-hardware', ...
    'acquisition-hardware', ...
    'hardware-interface', ...
    'measurement-supervision', ...
    'control-software'};
expectedStageUnits = {'V','count','deg','deg','deg'};
expectedBoundaryNames = { ...
    'sensor-to-adc', ...
    'adc-to-calibration', ...
    'calibration-to-quality', ...
    'quality-to-controller'};
assert(isequal(baseline.stageNames,expectedStageNames) && ...
    isequal(baseline.stageOwners,expectedStageOwners) && ...
    isequal(baseline.stageUnits,expectedStageUnits) && ...
    isequal(baseline.boundaryNames,expectedBoundaryNames), ...
    'P07 must preserve the declared stage, owner, unit, and boundary map.');
assert(baseline.stageCount == 5 && baseline.boundaryCount == 4 && ...
    baseline.minimumAdcBits == 4 && baseline.maximumAdcBits == 16 && ...
    baseline.maxAgeMs == 10000 && baseline.maxPhysicalAngleDeg == 360 && ...
    isequal(size(baseline.stageReached),[1 5]) && ...
    isequal(size(baseline.stageOutputValue),[1 5]) && ...
    isequal(size(baseline.boundaryCrossed),[1 4]), ...
    'The fixed five-stage, four-boundary resource envelope changed.');

expectedSensorVolts = 2.5 + 30/90;
expectedMaxAdcCount = 2^12 - 1;
expectedAdcCount = round((expectedSensorVolts - 0.5)/4*expectedMaxAdcCount);
expectedAngleDeg = -180 + 360*expectedAdcCount/expectedMaxAdcCount;
expectedQuantizationStepDeg = 360/expectedMaxAdcCount;
assert(abs(baseline.sensorVolts - expectedSensorVolts) < 1e-12 && ...
    baseline.maxAdcCount == expectedMaxAdcCount && ...
    baseline.adcCount == expectedAdcCount && ...
    abs(baseline.calibratedAngleDeg - expectedAngleDeg) < 1e-12 && ...
    abs(baseline.quantizationStepDeg - expectedQuantizationStepDeg) < 1e-12 && ...
    abs(baseline.quantizationErrorDeg) <= ...
    baseline.quantizationBoundDeg + 1e-12, ...
    'Baseline values must follow independent sensor, ADC, and calibration equations.');
assert(all(baseline.stageReached) && all(baseline.boundaryAttempted) && ...
    all(baseline.boundaryCrossed) && ~any(baseline.boundaryOpen) && ...
    baseline.deepestReachedStage == 5 && baseline.crossedBoundaryCount == 4 && ...
    baseline.entryPermitted && ~baseline.eventObserved && ...
    ~baseline.sensorSaturated && baseline.freshnessCriterionMet && ...
    baseline.freshnessMarginMs == 15 && baseline.qualityEvaluated && ...
    baseline.qualityValid && baseline.endpointReceived && ...
    baseline.endpointQualityValid && baseline.measurementUsable && ...
    baseline.payloadPreservedToEndpoint && ...
    baseline.qualityFlagPreservedToEndpoint && ...
    baseline.p06InputEligible && baseline.p06ScalarAdapterMet && ...
    baseline.p06ObservedAngleDeg == baseline.stageOutputValue(5) && ...
    baseline.reportedUsable && ~baseline.falseUsable && ...
    baseline.terminalOutcomeHandled && baseline.traceContractMet && ...
    strcmp(baseline.terminalStatus,'delivered-valid') && ...
    strcmp(baseline.failureMode,'none'), ...
    'The valid baseline must deliver an exact value and valid quality flag.');

adcBitChoices = [6 8 10 12];
expectedAdcCounts = [37 149 597 2389];
previousStepDeg = Inf;
for k = 1:numel(adcBitChoices)
    candidate = model(30,adcBitChoices(k),5,20, ...
        'none','none','complete');
    assertTraceInvariant(candidate);
    independentMaxCount = 2^adcBitChoices(k) - 1;
    independentCount = round(((2.5 + 30/90) - 0.5)/4* ...
        independentMaxCount);
    independentAngleDeg = -180 + 360*independentCount/independentMaxCount;
    assert(candidate.adcCount == expectedAdcCounts(k) && ...
        candidate.adcCount == independentCount && ...
        abs(candidate.calibratedAngleDeg - independentAngleDeg) < 1e-12 && ...
        abs(candidate.quantizationErrorDeg) <= ...
        0.5*candidate.quantizationStepDeg + 1e-12 && ...
        candidate.quantizationStepDeg < previousStepDeg, ...
        'Every ADC choice must follow the transparent count and half-LSB bound.');
    previousStepDeg = candidate.quantizationStepDeg;
end
