        negativeMaxBounded}
    assertTraceInvariant(candidate{1});
    assert(candidate{1}.endpointReceived && candidate{1}.sensorSaturated && ...
        candidate{1}.qualityEvaluated && ~candidate{1}.qualityValid && ...
        ~candidate{1}.measurementUsable && ~candidate{1}.reportedUsable && ...
        strcmp(candidate{1}.terminalStatus,'delivered-invalid') && ...
        strcmp(candidate{1}.failureMode,'sensor-saturated'), ...
        'Out-of-range truth must produce a received but invalid saturated sample.');
end
assert(maxBounded.adcCount == maxBounded.maxAdcCount && ...
    maxBounded.calibratedAngleDeg == 180 && ...
    negativeJustSaturated.adcCount == 0 && ...
    negativeMaxBounded.adcCount == 0 && ...
    negativeMaxBounded.calibratedAngleDeg == -180, ...
    'Both bounded input extremes must clip to the declared sensor full scale.');

