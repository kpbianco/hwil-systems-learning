maximumResolution = model(30,16,5,20,'none','none','complete');
assertTraceInvariant(minimumResolution);
assertTraceInvariant(maximumResolution);
assert(minimumResolution.maxAdcCount == 15 && ...
    maximumResolution.maxAdcCount == 65535 && ...
    minimumResolution.adcCount >= 0 && ...
    minimumResolution.adcCount <= minimumResolution.maxAdcCount && ...
    maximumResolution.adcCount >= 0 && ...
    maximumResolution.adcCount <= maximumResolution.maxAdcCount && ...
    maximumResolution.quantizationStepDeg < ...
    minimumResolution.quantizationStepDeg, ...
    'Minimum and maximum ADC settings must remain inside the resource bound.');

