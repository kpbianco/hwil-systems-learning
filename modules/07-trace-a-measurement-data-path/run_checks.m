function assertTraceInvariant(out)
assert(out.stageCount == 5 && out.boundaryCount == 4 && ...
    isequal(size(out.stageReached),[1 5]) && ...
    isequal(size(out.stageOutputValue),[1 5]) && ...
    isequal(size(out.boundaryAttempted),[1 4]) && ...
    isequal(size(out.boundaryCrossed),[1 4]) && ...
    isequal(size(out.boundaryOpen),[1 4]), ...
    'Every trace must stay inside the fixed resource envelope.');
assert(out.stageReached(1) == out.entryPermitted && ...
    isequal(out.stageReached(2:end),out.boundaryCrossed) && ...
    all(~out.boundaryCrossed | out.boundaryAttempted) && ...
    all(diff(double(out.stageReached)) <= 0), ...
    'Stage reachability must be an empty or contiguous prefix.');
assert(all(isfinite(out.stageOutputValue(out.stageReached))) && ...
    all(isnan(out.stageOutputValue(~out.stageReached))), ...
    'Reached stages need finite payloads and unreachable stages need no value.');
assert(out.deepestReachedStage == sum(out.stageReached) && ...
    out.crossedBoundaryCount == sum(out.boundaryCrossed), ...
    'Trace summary indices must derive from the visible Boolean arrays.');
if out.firstOpenBoundary > 0
    assert(out.boundaryAttempted(out.firstOpenBoundary) && ...
        out.boundaryOpen(out.firstOpenBoundary) && ...
        ~out.boundaryCrossed(out.firstOpenBoundary), ...
        'The first open boundary must be evaluated but not crossed.');
end
if out.stageReached(2)
    assert(out.adcCount == round(out.adcCount) && out.adcCount >= 0 && ...
        out.adcCount <= out.maxAdcCount, ...
        'A reached ADC stage must carry one bounded integer count.');
end
if out.stageReached(3)
    assert(isfinite(out.calibratedAngleDeg) && ...
        abs(out.quantizationErrorDeg) <= out.quantizationBoundDeg + 1e-12, ...
        'A calibrated sample must satisfy the declared half-LSB bound.');
end
assert(out.qualityEvaluated == out.stageReached(4) && ...
    out.measurementUsable == (out.endpointReceived && out.qualityValid), ...
    'Quality evaluation and factual usability must follow reachability.');
if out.qualityEvaluated
    assert(isfinite(out.freshnessMarginMs), ...
        'A reached qualification stage must evaluate freshness.');
else
    assert(~out.freshnessCriterionMet && isnan(out.freshnessMarginMs), ...
        'An unreached qualification stage must not report a freshness result.');
end
assert(out.p06InputEligible == out.measurementUsable && ...
    out.p06ScalarAdapterMet && ...
    ((out.p06InputEligible && isfinite(out.p06ObservedAngleDeg) && ...
    abs(out.p06ObservedAngleDeg) <= out.sensorFullScaleAngleDeg && ...
    out.p06ObservedAngleDeg == out.stageOutputValue(5)) || ...
    (~out.p06InputEligible && isnan(out.p06ObservedAngleDeg))), ...
    'P07 must gate the unchanged scalar P06 input without adding validity to it.');
if out.endpointReceived
    assert(out.stageReached(5) && out.payloadPreservedToEndpoint && ...
        out.qualityFlagPreservedToEndpoint && ...
        out.stageOutputValue(5) == out.stageOutputValue(4), ...
        'Endpoint receipt must preserve both value and quality.');
end
if out.eventObserved
    assert(~any(out.stageReached) && out.terminalOutcomeHandled && ...
        out.traceContractMet, ...
        'A handled acquisition-entry guard must create no sample.');
end
end

function expectAnyError(callable)
didThrow = false;
try
    callable();
catch
    didThrow = true;
end
assert(didThrow,'Malformed input must be rejected.');
end

function expectErrorId(callable,expectedId)
didThrow = false;
try
    callable();
catch exception
    didThrow = true;
    assert(strcmp(exception.identifier,expectedId), ...
        sprintf('Unexpected error identifier: %s',exception.identifier));
end
assert(didThrow,sprintf('Expected error %s was not raised.',expectedId));
end
