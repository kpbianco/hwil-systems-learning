nonzeroAgeZeroLimit = model(30,12,0.001,0,'none','none','complete');
maxAgeAtLimit = model(30,12,10000,10000,'none','none','complete');
for candidate = {ageAtLimit,ageJustOver,zeroAgeZeroLimit, ...
        nonzeroAgeZeroLimit,maxAgeAtLimit}
    assertTraceInvariant(candidate{1});
end
