negativeAngle = model(-30,12,5,20,'none','none','complete');
negativeFullScale = model(-180,12,5,20,'none','none','complete');
positiveFullScale = model(180,12,5,20,'none','none','complete');
for candidate = {zeroAngle,negativeAngle,negativeFullScale,positiveFullScale}
    assertTraceInvariant(candidate{1});
end
assert(abs(zeroAngle.quantizationErrorDeg) <= ...
    zeroAngle.quantizationBoundDeg + 1e-12 && zeroAngle.measurementUsable, ...
    'The zero-angle half-LSB case must remain bounded and usable.');
assert(abs(negativeAngle.calibratedAngleDeg + ...
    baseline.calibratedAngleDeg) < 1e-12 && negativeAngle.measurementUsable, ...
    'Signed angles must mirror through the symmetric measurement chain.');
assert(negativeFullScale.adcCount == 0 && ...
    negativeFullScale.calibratedAngleDeg == -180 && ...
    ~negativeFullScale.sensorSaturated && negativeFullScale.measurementUsable && ...
    positiveFullScale.adcCount == positiveFullScale.maxAdcCount && ...
    positiveFullScale.calibratedAngleDeg == 180 && ...
    ~positiveFullScale.sensorSaturated && positiveFullScale.measurementUsable, ...
    'Exact sensor full-scale endpoints must be valid inclusive limits.');

