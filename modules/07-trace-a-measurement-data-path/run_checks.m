    ageAtLimit.measurementUsable && ageAtLimit.freshnessMarginMs == 0 && ...
    zeroAgeZeroLimit.measurementUsable && maxAgeAtLimit.measurementUsable, ...
    'Freshness equality must pass at zero, nominal, and maximum bounded age.');
assert(~ageJustOver.freshnessCriterionMet && ~ageJustOver.qualityValid && ...
    ageJustOver.endpointReceived && ~ageJustOver.measurementUsable && ...
    strcmp(ageJustOver.failureMode,'stale-sample') && ...
    ~nonzeroAgeZeroLimit.measurementUsable, ...
    'A sample just beyond its supplied limit must be stale without disappearing.');
