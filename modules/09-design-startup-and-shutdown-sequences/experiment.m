%% P09 - Design Startup and Shutdown Sequences
close all; clc;
disp('Sequence question: which facts must be true before each startup or shutdown action is allowed?');
disp('Prediction: can the final running/off snapshots prove that every transient ordering was safe?');
disp('P08 supplies contract-conformance and input-eligibility facts; P09 orders their use without executing an interface.');

%% Baseline - read each guard before looking at the final state
baseline = model(5,6,true,true,'none','none','strict-order');
figure('Name','P09 baseline sequence guards and postconditions');
subplot(2,1,1);
bar(1:baseline.actionCount,double([baseline.startupPreconditionPass; ...
    baseline.startupPostconditionPass]')); grid on;
ylim([0 1.2]);
set(gca,'XTick',1:baseline.actionCount, ...
    'XTickLabel',baseline.startupActionNames,'XTickLabelRotation',20, ...
    'YTick',[0 1],'YTickLabel',{'Fail','Pass'});
xlabel('Startup action index (-)'); ylabel('Guard/result (Boolean -)');
title('Baseline startup: qualify P08 before actuator enable');
legend({'Precondition','Postcondition'},'Location','southoutside', ...
    'Orientation','horizontal');
subplot(2,1,2);
bar(1:baseline.actionCount,double([baseline.shutdownPreconditionPass; ...
    baseline.shutdownPostconditionPass]')); grid on;
ylim([0 1.2]);
set(gca,'XTick',1:baseline.actionCount, ...
    'XTickLabel',baseline.shutdownActionNames,'XTickLabelRotation',20, ...
    'YTick',[0 1],'YTickLabel',{'Fail','Pass'});
xlabel('Shutdown action index (-)'); ylabel('Guard/result (Boolean -)');
title('Baseline shutdown: confirm quiescence before power removal');
legend({'Precondition','Postcondition'},'Location','southoutside', ...
    'Orientation','horizontal');
assert(baseline.strictLifecycleAccepted && ...
    baseline.reportedLifecycleAccepted && ...
    baseline.startupEnableMissingPrerequisiteCount == 0 && ...
    baseline.shutdownPowerMissingPrerequisiteCount == 0 && ...
    baseline.totalViolationCount == 0, ...
    'Every baseline guard and postcondition must pass.');

%% Complementary baseline view - follow observable state, not just snapshots
lifecycleTrace = [baseline.startupStateTrace; ...
    baseline.shutdownStateTrace];
lifecycleLabels = [strcat('S:',baseline.startupActionNames) ...
    strcat('D:',baseline.shutdownActionNames)];
figure('Name','P09 baseline lifecycle state trace');
imagesc(lifecycleTrace'); colorbar; caxis([0 1]);
set(gca,'XTick',1:(2*baseline.actionCount), ...
    'XTickLabel',lifecycleLabels,'XTickLabelRotation',25, ...
    'YTick',1:baseline.stateCount,'YTickLabel',baseline.stateNames);
xlabel('Lifecycle action index (-)');
ylabel('Observable logical state (Boolean -)');
title('Baseline: running is reached through guards, then safe-off through guards');
assert(isequal(baseline.startupFinalState,[1 1 1 1 0 0 0]) && ...
    baseline.startupFinalRunning && ...
    isequal(baseline.shutdownFinalState,[0 0 0 0 1 1 1]) && ...
    baseline.shutdownFinalSafeOff, ...
    'The deterministic running and safe-off snapshots changed.');
fprintf(['Baseline metrics: startup enable position %d action, ' ...
    'shutdown power-off position %d action, startup violations %d count, ' ...
    'shutdown violations %d count, strict acceptance %d Boolean.\n'], ...
    baseline.inputs.startupEnablePosition, ...
    baseline.inputs.shutdownPowerOffPosition, ...
    baseline.startupViolationCount,baseline.shutdownViolationCount, ...
    baseline.strictLifecycleAccepted);

%% Sweep 1 - move only actuator-enable position in startup
startupPositionSweep = 1:5;
startupMissingByPosition = zeros(size(startupPositionSweep));
startupAcceptedByPosition = false(size(startupPositionSweep));
startupFinalRunningByPosition = false(size(startupPositionSweep));
for k = 1:numel(startupPositionSweep)
    trial = model(startupPositionSweep(k),6,true,true, ...
        'none','none','strict-order');
    startupMissingByPosition(k) = ...
        trial.startupEnableMissingPrerequisiteCount;
    startupAcceptedByPosition(k) = trial.strictLifecycleAccepted;
    startupFinalRunningByPosition(k) = trial.startupFinalRunning;
    fprintf(['Enable at action %d -> missing prerequisites %d count, ' ...
        'final running %d, strict acceptance %d.\n'], ...
        startupPositionSweep(k),startupMissingByPosition(k), ...
        trial.startupFinalRunning,trial.strictLifecycleAccepted);
    assert(trial.inputs.shutdownPowerOffPosition == 6 && ...
        trial.inputs.p08ContractConformant && ...
        trial.inputs.p08InputEligible && strcmp(trial.inputs.faultMode,'none'), ...
        'Sweep 1 must hold shutdown, P08 facts, and fault input fixed.');
end
figure('Name','P09 startup enable-position sweep');
yyaxis left;
plot(startupPositionSweep,startupMissingByPosition,'o-', ...
    'LineWidth',1.5,'MarkerFaceColor',[0.85 0.35 0.15]); grid on;
xlabel('Actuator-enable action position (-)');
ylabel('Missing enable prerequisites (count)');
yyaxis right;
stairs(startupPositionSweep,double(startupAcceptedByPosition), ...
    's-','LineWidth',1.5);
ylabel('Strict lifecycle acceptance (Boolean -)'); ylim([-0.1 1.1]);
title('Sweep 1: enable is valid only after power, controller, and P08 qualification');
assert(isequal(startupMissingByPosition,[3 3 2 1 0]) && ...
    isequal(startupAcceptedByPosition, ...
    [false false false false true]) && ...
    all(startupFinalRunningByPosition), ...
    'Startup position sweep must separate final state from ordered safety.');

%% Read and explain lever 1 before advancing
disp('Mechanism after lever 1: actuator enable consumes six visible facts; moving it earlier removes one or more proofs even when the later final running snapshot looks correct.');
disp('The P08 facts are logical prerequisite inputs, not evidence that a peer, transport, or hardware interface ran.');

%% Sweep 2 - reset startup and move only shutdown power removal
shutdownPositionSweep = 1:6;
shutdownMissingByPosition = zeros(size(shutdownPositionSweep));
shutdownAcceptedByPosition = false(size(shutdownPositionSweep));
shutdownFinalOffByPosition = false(size(shutdownPositionSweep));
for k = 1:numel(shutdownPositionSweep)
    trial = model(5,shutdownPositionSweep(k),true,true, ...
        'none','none','strict-order');
    shutdownMissingByPosition(k) = ...
        trial.shutdownPowerMissingPrerequisiteCount;
    shutdownAcceptedByPosition(k) = trial.strictLifecycleAccepted;
    shutdownFinalOffByPosition(k) = trial.shutdownFinalSafeOff;
    fprintf(['Power removal at action %d -> missing prerequisites %d count, ' ...
        'final safe-off %d, strict acceptance %d.\n'], ...
        shutdownPositionSweep(k),shutdownMissingByPosition(k), ...
        trial.shutdownFinalSafeOff,trial.strictLifecycleAccepted);
    assert(trial.inputs.startupEnablePosition == 5 && ...
        trial.inputs.p08ContractConformant && ...
        trial.inputs.p08InputEligible && strcmp(trial.inputs.faultMode,'none'), ...
        'Sweep 2 must reset startup and hold P08 and fault inputs fixed.');
end
figure('Name','P09 shutdown power-removal sweep');
yyaxis left;
plot(shutdownPositionSweep,shutdownMissingByPosition,'o-', ...
    'LineWidth',1.5,'MarkerFaceColor',[0.55 0.20 0.70]); grid on;
xlabel('Power-removal action position (-)');
ylabel('Missing power-removal prerequisites (count)');
yyaxis right;
stairs(shutdownPositionSweep,double(shutdownAcceptedByPosition), ...
    's-','LineWidth',1.5);
ylabel('Strict lifecycle acceptance (Boolean -)'); ylim([-0.1 1.1]);
title('Sweep 2: power removal follows inhibit, safe command, disable, quiescence, and close');
assert(isequal(shutdownMissingByPosition,[5 4 3 2 1 0]) && ...
    isequal(shutdownAcceptedByPosition, ...
    [false false false false false true]) && ...
    all(shutdownFinalOffByPosition), ...
    'Shutdown position sweep must expose every missing prerequisite.');

%% Read and explain lever 2 before advancing
disp('Mechanism after lever 2: removing power is safe in this logical model only after five observable prerequisites pass; a later final off snapshot cannot reconstruct their order.');
disp('Action index is dimensionless; it is not elapsed time. No milliseconds, latency, jitter, or distributed-clock behavior is modeled here.');

%% Negative cases - distinguish interface, actuator, and quiescence failures
contractInvalid = model(5,6,false,false,'none','none','strict-order');
qualityWithheld = model(5,6,true,false,'none','none','strict-order');
actuatorStuck = model(5,6,true,true, ...
    'actuator-stuck-on','none','strict-order');
quiescenceMissing = model(5,6,true,true, ...
    'quiescence-not-confirmed','none','strict-order');
assert(strcmp(contractInvalid.failureMode,'p08-contract-not-conformant') && ...
    ~contractInvalid.startupFinalRunning && ...
    strcmp(qualityWithheld.failureMode,'p08-input-not-eligible') && ...
    ~qualityWithheld.startupFinalRunning, ...
    'P08 conformance and input eligibility must remain distinct facts.');
assert(strcmp(actuatorStuck.failureMode,'actuator-disable-failed') && ...
    actuatorStuck.unsafePowerRemoval && ...
    ~actuatorStuck.shutdownFinalSafeOff && ...
    strcmp(quiescenceMissing.failureMode,'quiescence-not-confirmed') && ...
    quiescenceMissing.unsafePowerRemoval, ...
    'Shutdown postcondition failures must block strict acceptance.');

%% Cancellation, timeout, rollback, and recovery
cancelled = model(5,6,true,true,'none','cancellation','strict-order');
timedOut = model(5,6,true,true,'none','timeout','strict-order');
tied = model(5,6,true,true,'none', ...
    'cancellation-timeout-tie','strict-order');
for candidate = {cancelled,timedOut,tied}
    trial = candidate{1};
    assert(trial.rollbackPerformed && trial.rollbackSafeHold && ...
        all(trial.rollbackActionExecuted) && ...
        all(trial.rollbackPreconditionPass) && ...
        all(trial.rollbackPostconditionPass) && ...
        all(trial.rollbackStepPass) && ~any(trial.rollbackHazard) && ...
        isequal(trial.rollbackStateTrace(end,:),[0 0 0 0 1 1 1]) && ...
        strcmp(trial.rollbackFailureMode,'none') && ...
        ~trial.sequenceEvaluated && ...
        ~any(trial.shutdownActionEvaluated) && ...
        all(all(isnan(trial.shutdownStateTrace))) && ...
        all(isnan(trial.shutdownFinalState)), ...
        'A startup event must isolate shutdown and complete bounded rollback.');
end
assert(strcmp(cancelled.terminalStatus,'cancelled-safe-hold') && ...
    strcmp(timedOut.terminalStatus,'timed-out-safe-hold') && ...
    tied.tieResolvedToCancellation && ...
    strcmp(tied.terminalStatus,'cancelled-safe-hold'), ...
    'Cancellation must win the logical cancellation/timeout tie.');
cancelledStuck = model(1,6,true,true, ...
    'actuator-stuck-on','cancellation','strict-order');
timedOutNoQuiescence = model(5,6,true,true, ...
    'quiescence-not-confirmed','timeout','strict-order');
assert(~cancelledStuck.rollbackSafeHold && ...
    strcmp(cancelledStuck.terminalStatus, ...
    'cancelled-rollback-incomplete') && ...
    strcmp(cancelledStuck.rollbackFailureMode, ...
    'actuator-disable-failed') && ...
    ~timedOutNoQuiescence.rollbackSafeHold && ...
    strcmp(timedOutNoQuiescence.terminalStatus, ...
    'timed-out-rollback-incomplete') && ...
    strcmp(timedOutNoQuiescence.rollbackFailureMode, ...
    'quiescence-not-confirmed'), ...
    'Faulted compensation must report incomplete rollback, not safe hold.');
fprintf(['Faulted rollback examples: cancellation -> %s (%s); ' ...
    'timeout -> %s (%s).\n'],cancelledStuck.terminalStatus, ...
    cancelledStuck.rollbackFailureMode, ...
    timedOutNoQuiescence.terminalStatus, ...
    timedOutNoQuiescence.rollbackFailureMode);
recovered = model(5,6,true,true,'none','none','strict-order');
assert(isequaln(recovered,baseline), ...
    'A valid call after guarded events or failures must recover exactly.');

%% Broken case - final snapshots hide unsafe transient ordering
strictBroken = model(1,1,true,true,'none','none','strict-order');
broken = model(1,1,true,true,'none','none','final-state-only');
figure('Name','P09 deliberately broken final-state-only assessment');
bar(1:3,double([broken.startupFinalRunning ...
    broken.shutdownFinalSafeOff broken.reportedLifecycleAccepted]));
grid on; ylim([0 1.2]);
set(gca,'XTick',1:3,'XTickLabel', ...
    {'Final running','Final safe-off','Broken approval'}, ...
    'YTick',[0 1],'YTickLabel',{'False','True'});
xlabel('Final-snapshot assessment (-)');
ylabel('Reported result (Boolean -)');
title('Broken case: correct-looking snapshots conceal order violations');
assert(isequaln(strictBroken.startupStateTrace, ...
    broken.startupStateTrace) && ...
    isequaln(strictBroken.shutdownStateTrace, ...
    broken.shutdownStateTrace) && ...
    strictBroken.startupFinalRunning && strictBroken.shutdownFinalSafeOff && ...
    ~strictBroken.strictLifecycleAccepted && ...
    ~strictBroken.reportedLifecycleAccepted && ...
    broken.snapshotLifecycleAccepted && ...
    broken.reportedLifecycleAccepted && broken.falseApproval && ...
    ~broken.assessmentDecisionCorrect && ...
    strcmp(broken.reportingFailureMode, ...
    'final-state-only-false-approval'), ...
    'The broken assessor must change only the report and expose false approval.');
disp('Broken mechanism: checking only the final running and off snapshots discards the transient evidence that enable and power removal occurred before their prerequisites.');

